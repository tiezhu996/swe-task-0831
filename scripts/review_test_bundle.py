def sha256(path: Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as stream:
        for chunk in iter(lambda: stream.read(1024 * 1024), b""):
            digest.update(chunk)
    return digest.hexdigest()


def git(repo: Path, *args: str) -> str:
    result = subprocess.run(
        ["git", "-C", str(repo), *args],
        check=True,
        capture_output=True,
        text=True,
    )
    return result.stdout.strip()


def safe_zip_name(name: str) -> bool:
    if "\\" in name or re.match(r"^[A-Za-z]:", name):
        return False
    path = PurePosixPath(name)
    raw_parts = name.rstrip("/").split("/")
    return not path.is_absolute() and all(part not in ("", ".", "..") for part in raw_parts)


def fairness_evidence_check(path: Path | None) -> tuple[bool, str]:
    if path is None or not path.is_file():
        return False, "缺少公平性证据文件（--fairness-evidence）"
    try:
        data = json.loads(path.read_text(encoding="utf-8"))
    except (OSError, json.JSONDecodeError) as exc:
        return False, f"公平性证据无法解析：{exc}"
    probes = data.get("probes")
    if not isinstance(probes, dict):
        return False, "公平性证据缺少 probes 对象"
    required_positive = [
        "order_variant",
        "enum_variant",
        "error_variant",
        "p2p_import_export",
        "json_field_alias",
        "git_fallback",
        "zero_hit",
        "multi_kind_counts",
        "existing_test_regression",
        "pretty_json",
    ]
    required_negative = [
        "error_vague",
        "error_panic",
        "error_generic",
        "target_echo_only",
        "tempfile_write",
        "stub_output",
        "merged_kinds",
    ]
    required = required_positive + required_negative
    missing = [name for name in required if name not in probes]
    if missing:
        return False, "缺少公平性探针：" + ", ".join(missing)
    problems: list[str] = []
    for name in required_positive:
        item = probes.get(name)
        if not isinstance(item, dict):
            problems.append(f"{name} 不是对象")
            continue
        result = str(item.get("result", "")).strip().lower()
        if result not in {"pass", "passed", "ok", "success"}:
            problems.append(f"{name} result={result or 'missing'}")
        if item.get("reward") != 1:
            problems.append(f"{name} reward={item.get('reward')}")
        evidence = item.get("evidence")
        if not evidence:
            problems.append(f"{name} evidence 缺失")
            continue
        evidence_path = Path(str(evidence))
        if not evidence_path.is_absolute():
            evidence_path = path.parent / evidence_path
        if not evidence_path.is_file():
            problems.append(f"{name} evidence 不存在：{evidence}")
    for name in required_negative:
        item = probes.get(name)
        if not isinstance(item, dict):
            problems.append(f"{name} 不是对象")
            continue
        result = str(item.get("result", "")).strip().lower()
        if result not in {"fail", "failed", "blocked", "rejected"}:
            problems.append(f"{name} result={result or 'missing'}，负向探针必须被拦截")
        if item.get("reward") != 0:
            problems.append(f"{name} reward={item.get('reward')}，负向探针必须为 0")
        evidence = item.get("evidence")
        if not evidence:
            problems.append(f"{name} evidence 缺失")
            continue
        evidence_path = Path(str(evidence))
        if not evidence_path.is_absolute():
            evidence_path = path.parent / evidence_path
        if not evidence_path.is_file():
            problems.append(f"{name} evidence 不存在：{evidence}")
    if problems:
        return False, "；".join(problems)
    return True, "排序/枚举/错误文案/字段别名/无 git 回退与两类负向错误探针齐全"


def patch_source_sync_check(tests_dir: Path) -> tuple[bool, str]:
    delivery = tests_dir / "deliverytests"
    patch = tests_dir / "test.patch"
    if not delivery.is_dir():
        return True, "交付包不包含独立 deliverytests 目录；test.patch 是唯一测试源"
    go_files = sorted(delivery.glob("*.go"))
    if not go_files:
        return False, "deliverytests 目录存在但没有 Go 源文件"
    with tempfile.TemporaryDirectory(prefix="test-patch-sync-") as tmp:
        root = Path(tmp)
        result = subprocess.run(
            ["git", "apply", str(patch)],
            cwd=root, capture_output=True, text=True,
        )
        if result.returncode:
            return False, "无法在临时目录应用 test.patch：" + (result.stderr or result.stdout).strip()
        injected = root / "internal" / "deliverytests"
        for path in go_files:
            target = injected / path.name
            if not target.is_file() or target.read_bytes() != path.read_bytes():
                return False, f"test.patch 注入的 {path.name} 与 deliverytests/{path.name} 不一致"
    return True, "test.patch 注入的 Go 源与 deliverytests 逐字一致"


def git_fallback_check(script_text: str) -> tuple[bool, str]:
    uses_archive = bool(re.search(r"git\s+-C[^\n]*archive|git\s+archive", script_text))
    if not uses_archive:
        return True, "入口不依赖 git archive"
    has_fallback = bool(re.search(r"TESTS_DIR/deliverytests", script_text)) and bool(
        re.search(r"TEST_SOURCE=\"?(packaged|packaged-source|packaged_tests)\"?", script_text)
    )
    if not has_fallback:
        return False, "入口依赖 git archive 但没有 packaged deliverytests 回退；/app 无 .git 时正确候选会 execution_error"
    return True, "git archive 失败时回退到交付包自带 deliverytests"


def cache_artifact_hits(tests_dir: Path) -> list[str]:
    hits: list[str] = []
    suffixes = {".pyc", ".pyo", ".o", ".a", ".so", ".test", ".exe", ".dll", ".dylib"}
    for path in tests_dir.rglob("*"):
        if not path.is_file():
            continue
        rel = path.relative_to(tests_dir).as_posix()
        if "__pycache__/" in rel or path.name == ".DS_Store" or path.suffix.lower() in suffixes:
            hits.append(rel)
    return hits


def literal_binding_hits(source_files: list[Path], tests_dir: Path) -> list[str]:
    patterns = [
        ("rule_sort", r"strict(?:ly)?\s+sorted"),
        ("enum_session", r"want\s+\"session\""),
        ("enum_file", r"want\s+\"file\""),
        ("source_enum", r"source\s*[!=]=\s*\"(?:transcript|file)\""),
        ("target_type_binding", r"Target\.Type\s*[!=]="),
        ("error_text_session", r"no\s+session\s+matches"),
        ("error_text_target", r"needs\s+a\s+session\s+id-prefix"),
    ]
    hits: list[str] = []
    for path in source_files:
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        for label, pattern in patterns:
            if re.search(pattern, text, re.IGNORECASE):
                hits.append(f"{path.relative_to(tests_dir).as_posix()}:{label}")
    return hits


def review(args: argparse.Namespace) -> dict:
    tests_dir = args.tests_dir.resolve()
    bundle = args.zip.resolve()
    defense = args.defense.resolve()
    base_repo = args.base_repo.resolve()
    checks: list[dict] = []
    blockers: list[str] = []

    def add(name: str, ok: bool, detail: str) -> None:
        checks.append({"name": name, "status": "PASS" if ok else "FAIL", "detail": detail})
        if not ok:
            blockers.append(name)

    def report(status: str) -> dict:
        return {
            "schema_version": 1,
            "review_kind": "test_bundle_static_preflight",
            "status": status,
            "submission_ready": False,
            "task_id": None,
            "base_commit": args.base_commit,
            "zip": str(bundle),
            "zip_sha256": sha256(bundle) if bundle.is_file() else None,
            "tests_dir": str(tests_dir),
            "defense": str(defense),
            "checks": checks,
            "blockers": blockers,
            "manual_gates": [
                "在指定目标容器中运行解压后的最终 ZIP，并保存命令、镜像标识、stdout/stderr、退出码和哈希。",
                "用固定基线、完整参考实现、历史候选和针对性错误实现进行校准；把编译未执行与测试失败分开记录。",
                "将冻结 Rubric 逐项映射到测试名称、场景、断言、证据和缺口；任何 partial/missing 都不得标为 READY。",
                "对照平台历史产物结果：每个历史未通过的 Rubric 都要在历史候选上有对应的失败用例。",
                "在目标镜像中实测写入隔离探针：候选 init() 改写 grader 或伪造 reward 必须失败。",
                "变异探针需证明命中被改分支，并配合理替代实现的误杀探针。",
                "在上一版镜像复现、在新版镜像复验同一攻击探针：改写注入测试源码、替换评分二进制、经 /proc 伪造事件、延迟写 reward。",
                "P2P 回归在目标镜像实测三个探针：改坏业务函数（P2P 必须下降）、同时禁用测试辅助断言（仍须下降）、提交包加入“在 *.test 进程内即崩溃”的 init（各套件须正常完成，证明评分二进制不含提交代码）。",
                "逐条核对历次审核报告的全部未关闭项，并把同一基线/同一入口的其他任务一并检查，不能只修本次报告点名的问题。",
                "公平性门禁：对排序、JSON 枚举取值、错误文案各做一个等价实现变体，得分必须与参考实现一致；不得把参考实现的未公开选择写成硬契约。",
                "回归覆盖门禁：题面明确提到的入口（如导入/导出/摘要）都必须有黑盒 P2P 或等价回归证据，不能只覆盖相邻命令。",
                "错误质量门禁：错误场景不能只断言非零退出和 stderr 非空；必须能拒绝 vague error 和 panic/stack trace，负向探针 error_vague/error_panic 必须被拦截。",
                "JSON 公平性门禁：字段名必须按仓库既有 JSON 约定做别名匹配（例如 rules/hits、kind/type、snippets/matches）；字段别名等价实现必须通过。",
                "进程级只读门禁：只读断言必须覆盖 TMPDIR、HOME、当前工作目录等进程可写位置，不能只快照夹具根目录；tempfile_write 负向探针必须 reward=0。",
                "错误双条件门禁：错误必须同时包含失败目标和具体原因；只回显目标或只给泛化名词都不算，target_echo_only 负向探针必须 reward=0。",
                "多行 JSON 门禁：机器可读输出解析必须接受多行/pretty JSON 和前置诊断，不能只查找单行 {；pretty_json 正向探针必须 reward=1。",
                "输入耦合门禁：F2P 断言必须与输入内容绑定，至少覆盖零命中负例、多变体正例和多类型/多数量正例；固定输出 stub、合并类型/计数的实现必须被拦截。",
                "独立真值门禁：计数、类型和摘要必须与独立可观察路径（索引、share、导出归档、读回状态）交叉核对，不能只比较候选自己的多次输出。",
                "错误特异性门禁：错误必须含失败目标或具体原因；file/session/usage 这类泛化名词不算；error_generic 负向探针必须 reward=0。",
                "既有测试闭环门禁：Rubric 声称既有测试保持通过时，入口必须实际执行，或提供逐项黑盒替代映射；不能只在文档里声称。",
                "交付卫生门禁：ZIP 不得包含 __pycache__、*.pyc/*.pyo、.DS_Store 或构建二进制；死件与缓存件都阻断。",
                "构建独立性门禁：入口不得硬依赖 /app 的 .git；git archive 不可用时必须有交付包自带 deliverytests 的可信回退，不能让正确候选 execution_error。",
                "交付件同步门禁：test.patch 与 deliverytests 同时存在时，注入的 Go 源必须逐字一致；不得保留未使用的死件。",
                "复审答辩文档每项事实是否能回指本次运行证据；写明复审人、时间、版本哈希和最终 READY/HOLD。",
            ],
            "reviewed_at": datetime.now(timezone.utc).isoformat(),
        }

    if not tests_dir.is_dir():
        add("tests_directory", False, f"目录不存在：{tests_dir}")
        return report("HOLD")
    if not bundle.is_file():
        add("zip_exists", False, f"文件不存在：{bundle}")
        return report("HOLD")

    source_files = sorted(p for p in tests_dir.rglob("*") if p.is_file())
    symlink_sources = [p for p in tests_dir.rglob("*") if p.is_symlink()]
    source_relatives = {p.relative_to(tests_dir).as_posix() for p in source_files}
    missing = sorted(REQUIRED_FILES - source_relatives)
    add("required_files", not missing, "缺少：" + ", ".join(missing) if missing else "必需文件齐全")
    add("source_symlinks", not symlink_sources, "测试目录不允许符号链接" if symlink_sources else "未发现符号链接")
    cache_hits = cache_artifact_hits(tests_dir)
    add(
        "cache_artifact_scan",
        not cache_hits,
        "未发现缓存或构建产物" if not cache_hits else
        "交付包含缓存/构建产物：" + ", ".join(cache_hits[:8]),
    )
    patch_path = tests_dir / "test.patch"
    add("test_patch_nonempty", patch_path.is_file() and patch_path.stat().st_size > 0, "test.patch 非空" if patch_path.is_file() and patch_path.stat().st_size > 0 else "test.patch 缺失或为空")

    archive_map: dict[str, bytes] = {}
    zip_errors: list[str] = []
    try:
        with zipfile.ZipFile(bundle) as archive:
            bad_member = archive.testzip()
            if bad_member:
                zip_errors.append(f"CRC 校验失败：{bad_member}")
            seen_members: set[str] = set()
            for info in archive.infolist():
                if not safe_zip_name(info.filename) or not info.filename.startswith("tests/"):
                    zip_errors.append(f"非法或越界路径：{info.filename}")
                    continue
                if stat.S_ISLNK(info.external_attr >> 16):
                    zip_errors.append(f"不允许符号链接成员：{info.filename}")
                    continue
                if info.is_dir():
                    continue
                if info.filename in seen_members:
                    zip_errors.append(f"ZIP 中存在重名文件：{info.filename}")
                    continue
                seen_members.add(info.filename)
                archive_map[info.filename.removeprefix("tests/")] = archive.read(info)
    except (OSError, RuntimeError, zipfile.BadZipFile) as exc:
        zip_errors.append(str(exc))
    add("zip_safety", not zip_errors, "; ".join(zip_errors) if zip_errors else "ZIP 完整且成员均位于 tests/ 下")

    source_map = {p.relative_to(tests_dir).as_posix(): p.read_bytes() for p in source_files}
    same_files = source_map == archive_map
    add(
        "zip_matches_staging",
        same_files,
        "ZIP 与 tests 目录逐文件一致" if same_files else
        f"仅在目录中：{sorted(source_map.keys() - archive_map.keys())}; 仅在 ZIP 中：{sorted(archive_map.keys() - source_map.keys())}; 内容不同：{sorted(k for k in source_map.keys() & archive_map.keys() if source_map[k] != archive_map[k])}",
    )

    config_path = tests_dir / "config.json"
    config: dict = {}
    try:
        config = json.loads(config_path.read_text(encoding="utf-8"))
        buckets = {key: config.get(key) for key in ("f2p_node_ids", "p2p_node_ids")}
        valid_buckets = all(isinstance(ids, list) and ids and all(isinstance(i, str) and i.strip() for i in ids) for ids in buckets.values())
        ids = [item.strip() for group in buckets.values() if isinstance(group, list) for item in group if isinstance(item, str)]
        unique_ids = len(ids) == len(set(ids))
        reports = config.get("grade", {}).get("reports", [])
        run_scoped = isinstance(reports, list) and bool(reports) and all("$RUN_DIR" in str(item) for item in reports)
        base_matches = config.get("base_commit") == args.base_commit
        config_ok = valid_buckets and unique_ids and run_scoped and base_matches
        details = f"task_id={config.get('task_id')}; F2P={len(buckets['f2p_node_ids']) if isinstance(buckets['f2p_node_ids'], list) else 0}; P2P={len(buckets['p2p_node_ids']) if isinstance(buckets['p2p_node_ids'], list) else 0}; IDs 唯一={unique_ids}; 报告按 RUN_DIR 隔离={run_scoped}; 基线匹配={base_matches}"
    except Exception as exc:
        config_ok, details = False, f"config.json 解析失败：{exc}"
    add("config_contract", config_ok, details)

    script = tests_dir / "test.sh"
    shell_ok = False
    if script.is_file():
        result = subprocess.run(["bash", "-n", str(script)], capture_output=True, text=True)
        shell_ok = result.returncode == 0
        shell_detail = "bash -n 通过" if shell_ok else (result.stderr.strip() or result.stdout.strip())
    else:
        shell_detail = "test.sh 不存在"
    add("shell_syntax", shell_ok, shell_detail)

    script_text = script.read_text(encoding="utf-8") if script.is_file() else ""
    drops = re.search(r"\b(setpriv|runuser|gosu|su-exec)\b", script_text)
    add(
        "candidate_isolation",
        bool(drops),
        f"test.sh 使用 {drops.group(1)} 降权运行候选" if drops else "test.sh 未降权运行候选代码；候选可能改写 grader 或伪造 reward",
    )
    # Scored test binaries must not be compiled inside the tree the candidate controls
    # after it has been handed to the candidate account.
    compiled_before = bool(re.search(r"go\s+test\s+-c\b", script_text))
    candidate_go_test = re.search(r"(as_candidate|as_runner|setpriv[^\n]*)\s+(env\s+[^\n]*\s+)?go\s+test\b", script_text)
    # Every scored test binary, P2P included, is compiled from the pristine baseline tree
    # plus test.patch. Restoring baseline *_test.go is not enough: submitted package code
    # (init functions, build-tagged helpers) still links into the binary and can write
    # test events or neuter assertions before any test runs.
    untrusted_builds = [line.strip() for line in script_text.splitlines()
                        if re.search(r"go\s+test\s+-c\b", line) and not re.search(r"(?i)pristine", line)]
    add(
        "p2p_tests_from_trusted_source",
        not untrusted_builds,
        "所有评分测试二进制均从干净基线 + test.patch 编译，不链接任何提交代码" if not untrusted_builds else
        "评分测试二进制在候选树中编译，会链接提交的业务包（init 可伪造事件、测试辅助代码可被替换）：" + "; ".join(untrusted_builds[:3]),
    )
    pipe_unchecked = bool(re.search(r"test2json", script_text)) and not re.search(r"(PIPESTATUS\[1\]|\{statuses\[1\]\}|t2j)", script_text)
    add(
        "converter_exit_checked",
        not pipe_unchecked,
        "test2json 转换器退出码被检查" if not pipe_unchecked else
        "test2json 退出码未检查，转换器故障会被当作候选结果",
    )
    add(
        "scored_binaries_precompiled",
        compiled_before and not candidate_go_test,
        "评分测试由可信步骤预编译（go test -c），候选账号只运行二进制" if compiled_before and not candidate_go_test else
        "候选账号直接运行 go test，或未预编译评分测试；候选可在运行期改写注入的测试源码",
    )
    dockerfile = tests_dir / "Dockerfile"
    froms = re.findall(r"(?im)^\s*FROM\s+(\S+)", dockerfile.read_text(encoding="utf-8")) if dockerfile.is_file() else []
    unpinned = [image for image in froms if "@sha256:" not in image]
    add("base_image_pinned", bool(froms) and not unpinned, "基础镜像均以 digest 固定" if froms and not unpinned else "未以 @sha256 固定：" + ", ".join(unpinned or ["缺少 FROM"]))
    unguarded: list[str] = []
    if re.search(r"(?m)^\s*set\s+-[a-z]*u", script_text):
        for name in sorted(set(re.findall(r"(?m)^\s*(\w+)=\(\)", script_text))):
            plain = len(re.findall(r'"\$\{' + name + r'\[@\]\}"', script_text))
            guarded = len(re.findall(r'\$\{' + name + r'\[@\]\+"\$\{' + name + r'\[@\]\}"\}', script_text))
            if plain > guarded:
                unguarded.append(name)
    add("empty_array_expansion", not unguarded, "set -u 下的空数组展开均有保护" if not unguarded else "可能为空的数组在 set -u 下直接展开：" + ", ".join(unguarded))
    lines = [line.strip() for line in script_text.splitlines() if line.strip() and not line.strip().startswith("#")]
    add("entry_exit_status", not lines or lines[-1] not in ("exit 0", "exit"), "入口末尾不是无条件成功退出" if not lines or lines[-1] not in ("exit 0", "exit") else "test.sh 以无条件 exit 0 结束")

    python_files = sorted(tests_dir.rglob("*.py"))
    python_errors: list[str] = []
    for path in python_files:
        try:
            ast.parse(path.read_text(encoding="utf-8"), filename=str(path))
        except (OSError, SyntaxError) as exc:
            python_errors.append(f"{path.name}: {exc}")
    if script.is_file():
        for index, body in enumerate(PY_HEREDOC.findall(script.read_text(encoding="utf-8")), 1):
            try:
                ast.parse(body, filename=f"{script.name}:python-heredoc-{index}")
            except SyntaxError as exc:
                python_errors.append(f"{script.name} heredoc {index}: {exc}")
    patch_used = ("test.patch" in script_text) and bool(re.search(r"git\s+apply|patch\s+-p1", script_text))
    add(
        "test_patch_used",
        patch_used,
        "test.patch 被入口通过 git apply/patch 实际消费" if patch_used else
        "test.patch 存在但没有被 test.sh 消费；不得交付一份不会运行的测试补丁",
    )

    sync_ok, sync_detail = patch_source_sync_check(tests_dir)
    add("patch_source_sync", sync_ok, sync_detail)

    git_ok, git_detail = git_fallback_check(script_text)
    add("git_fallback", git_ok, git_detail)

    binding_hits = literal_binding_hits(source_files, tests_dir)
    add(
        "literal_binding_scan",
        not binding_hits,
        "未发现把参考实现的未公开排序、枚举值或错误文案写成硬契约" if not binding_hits else
        "发现未公开契约字面量硬绑定：" + ", ".join(binding_hits[:8]),
    )

    fairness_ok, fairness_detail = fairness_evidence_check(getattr(args, "fairness_evidence", None))
    add("fairness_evidence", fairness_ok, fairness_detail)

    add("python_syntax", not python_errors, "; ".join(python_errors) if python_errors else "Python 文件和 test.sh 内嵌 Python 均可解析")

    text_hits: list[str] = []
    for path in source_files:
        try:
            text = path.read_text(encoding="utf-8")
        except UnicodeDecodeError:
            continue
        if AI_TEXT.search(text):
            text_hits.append(path.relative_to(tests_dir).as_posix())
    add("restricted_copy_scan", not text_hits, "命中：" + ", ".join(text_hits) if text_hits else "未发现禁用文案")

    base_errors: list[str] = []
    try:
        head = git(base_repo, "rev-parse", "HEAD")
        dirty = git(base_repo, "status", "--porcelain")
        if head != args.base_commit:
            base_errors.append(f"HEAD={head}，预期={args.base_commit}")
        if dirty:
            base_errors.append("基线工作树不干净")
        apply = subprocess.run(
            ["git", "-C", str(base_repo), "apply", "--check", str(tests_dir / "test.patch")],
            capture_output=True,
            text=True,
        )
        if apply.returncode:
            base_errors.append((apply.stderr or apply.stdout).strip() or "git apply --check 失败")
    except (OSError, subprocess.CalledProcessError) as exc:
        base_errors.append(f"无法读取基线仓库：{exc}")
    add("base_patch_check", not base_errors, "; ".join(base_errors) if base_errors else "基线 HEAD 匹配、工作树干净、test.patch 可应用")

    defense_ok = defense.is_file() and str(config.get("task_id", "")) in defense.read_text(encoding="utf-8")
    add("defense_identity", defense_ok, "答辩文档存在并包含 config.json 的 task_id" if defense_ok else "答辩文档缺失或题号与 config.json 不匹配")

    all_static = not blockers
    result = report("STATIC_PASS" if all_static else "HOLD")
    result["task_id"] = config.get("task_id")
    return result


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--tests-dir", type=Path, required=True, help="已冻结 tests/ 目录")
    parser.add_argument("--zip", type=Path, required=True, help="最终待交付 testzip")
    parser.add_argument("--base-repo", type=Path, required=True, help="HEAD 位于指定基线且工作树干净的仓库")
    parser.add_argument("--base-commit", required=True, help="config.json 中的固定基线 commit")
    parser.add_argument("--fairness-evidence", type=Path, required=True, help="排序/枚举/错误文案等价探针与导入导出 P2P 证据 JSON")
    parser.add_argument("--defense", type=Path, required=True, help="对应题号的答辩文档")
    parser.add_argument("--out", type=Path, required=True, help="复审 JSON 输出路径")
    args = parser.parse_args()

    report = review(args)
    args.out.parent.mkdir(parents=True, exist_ok=True)
    temp = args.out.with_suffix(args.out.suffix + ".tmp")
    temp.write_text(json.dumps(report, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    temp.replace(args.out)
    for item in report["checks"]:
        print(f"{item['status']} {item['name']}: {item['detail']}")
    print(f"{report['status']} submission_ready=false zip_sha256={report['zip_sha256']}")
    return 0 if report["status"] == "STATIC_PASS" else 1


if __name__ == "__main__":
    sys.exit(main())
